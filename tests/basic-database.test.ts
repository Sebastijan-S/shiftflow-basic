import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
import { createDemo } from "../src/lib/demo";
import { generateSchedule, addDays } from "../src/lib/scheduler";
import { cloudState, type StoredState } from "../src/lib/storage";

test("Basic database: four tenants, idempotent saves, history, absences, published snapshots and invitations", async () => {
  const db = await PGlite.create();
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth;
      create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,raw_user_meta_data jsonb not null default '{}');
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      grant usage on schema public,auth to anon,authenticated; grant execute on function auth.uid() to anon,authenticated;`);
    for (const name of ["202611030001_shiftflow.sql", "20261114180614_shiftflow_basic.sql", "20261114182256_shiftflow_access_hardening.sql", "20261114183109_shiftflow_notification_events.sql"]) await db.exec(await readFile(`supabase/migrations/${name}`, "utf8"));
    const users = [1, 2, 3, 4].map(n => `00000000-0000-0000-0000-${String(n).padStart(12, "0")}`);
    for (const id of users) await db.query("insert into auth.users(id,email,email_confirmed_at,raw_user_meta_data) values($1,$2,now(),$3)", [id, `${id}@example.test`, JSON.stringify({ company_name: "Pilot" })]);
    const memberships = (await db.query<{ user_id: string; company_id: string }>("select user_id,company_id from memberships")).rows;
    assert.equal(new Set(memberships.map(m => m.company_id)).size, 4);
    const company = memberships.find(m => m.user_id === users[0])!.company_id;
    const signIn = async (user: string) => { await db.exec("set role authenticated"); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [user]); };
    await signIn(users[0]);
    assert.equal((await db.query("select * from companies")).rows.length, 1);
    const current = createDemo(); current.positions = ["Barista", "Konobar", "Menadžer", "Kuvar"];
    const week = Object.keys(current.schedules)[0]; current.schedules[week].status = "published";
    current.schedules[week].assignments[0].note = "INTERNO";
    let state = cloudState({ schema: 2, revision: 1, current, past: [], future: [] });
    let version = 0;
    const save = async (s: StoredState, id = crypto.randomUUID()) => {
      const next = Number((await db.query<{ v: number }>("select save_workspace_v2($1,$2::jsonb,$3,$4) as v", [company, JSON.stringify(s), version, id])).rows[0].v);
      version = next; return next;
    };
    const operation = crypto.randomUUID();
    await save(state, operation);
    assert.equal(await save(state, operation), 1, "lost response can retry without another audit event");
    assert.equal((await db.query("select * from change_history")).rows.length, 1);
    await assert.rejects(db.query("select save_workspace_v2($1,$2::jsonb,0,$3)", [company, JSON.stringify(state), crypto.randomUUID()]), /VERSION_CONFLICT/);
    const duplicated = structuredClone(state); duplicated.current.schedules[week].assignments.push(duplicated.current.schedules[week].assignments[0]);
    await assert.rejects(save(duplicated), /DUPLICATE_ASSIGNMENT_IDS/);
    const token = (await db.query<{ t: string }>("select rotate_schedule_link($1,$2) as t", [company, week])).rows[0].t;
    const before = (await db.query<{ p: unknown }>("select read_shared_schedule($1) p", [token])).rows[0].p;
    assert.ok(before); assert.ok(!JSON.stringify(before).includes("INTERNO"));
    const draft = structuredClone(state); draft.revision++; draft.current.schedules[week] = generateSchedule(draft.current, week);
    await save(draft);
    assert.deepEqual((await db.query<{ p: unknown }>("select read_shared_schedule($1) p", [token])).rows[0].p, before, "new draft preserves last publication");
    state = structuredClone(draft); state.current.templates[0].end = "14:00"; state.current.employees[0].active = false; state.revision++;
    await save(state);
    assert.deepEqual((await db.query<{ p: unknown }>("select read_shared_schedule($1) p", [token])).rows[0].p, before, "published projection is historical");
    const absent = structuredClone(draft); absent.revision++;
    const a = absent.current.schedules[week].assignments[0];
    absent.current.absences = [{ id: crypto.randomUUID(), employeeId: a.employeeId, from: addDays(week, a.day), to: addDays(week, a.day), kind: "absence", reason: "Odmor" }];
    absent.current.schedules[week].status = "published";
    await assert.rejects(save(absent), /EMPLOYEE_ABSENT/);
    assert.equal(Number((await db.query<{ n: number }>("select count(*) n from absences")).rows[0].n), 0, "rejected publication rolls back all changes");
    const invitation = (await db.query<{ t: string }>("select create_manager_invitation($1,$2) t", [company, `${users[1]}@example.test`])).rows[0].t;
    await signIn(users[1]);
    await db.query("select accept_manager_invitation($1)", [invitation]);
    assert.equal((await db.query("select * from memberships where user_id=$1", [users[1]])).rows.length, 2);
    const changed = structuredClone(state); changed.current.rules.minRestHours = 8; changed.revision++;
    await save(changed);
    const rename = structuredClone(changed); rename.current.name = "Neovlašćeni naziv";
    await assert.rejects(save(rename), /OWNER_REQUIRED/);
    await signIn(users[0]); await db.query("select remove_manager($1,$2)", [company, users[1]]);
    await signIn(users[1]);
    await assert.rejects(save(changed), /ACCESS_DENIED/);
    await db.exec("set role anon");
    await assert.rejects(db.query("select * from published_schedules"), /permission denied/);
    assert.ok((await db.query<{ p: unknown }>("select read_shared_schedule($1) p", [token])).rows[0].p);
  } finally { await db.close(); }
});
